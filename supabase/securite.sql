-- Numéro de commande court, à communiquer au client pour le suivi.
alter table orders add column if not exists order_number bigint generated by default as identity;
create unique index if not exists orders_order_number_idx on orders (order_number);

-- Moyen de paiement choisi par le client et suivi du paiement par l'admin.
alter table orders add column if not exists payment_method text not null default 'cash';
alter table orders add column if not exists paid boolean not null default false;
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'orders_payment_method_check') then
    alter table orders add constraint orders_payment_method_check
      check (payment_method in ('mtn_momo', 'moov_money', 'celtiis_cash', 'cash'));
  end if;
end $$;
create index if not exists orders_created_at_idx on orders (created_at);

-- Les avis ne sont plus publiés automatiquement : validation dans l'admin.
alter table product_reviews alter column approved set default false;


