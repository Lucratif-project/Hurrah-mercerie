create policy hm_public_insert on product_reviews for insert with check (
  approved = false
  and rating between 1 and 5
  and char_length(author_name) between 1 and 80
  and (comment is null or char_length(comment) <= 1000)
  and exists (select 1 from products p where p.id = product_id and p.status = 'published')
);

