-- On supprime d'abord les règles de ce script (pour pouvoir le relancer).
do $$
declare r record;
begin
  for r in
    select policyname, tablename from pg_policies
    where schemaname = 'public' and policyname like 'hm_%'
  loop
    execute format('drop policy %I on public.%I', r.policyname, r.tablename);
  end loop;
end $$;

-- Administrateurs : tout est permis sur toutes les tables.
do $$
declare t text;
begin
  foreach t in array array[
    'categories','products','product_images','orders','order_items',
    'admin_users','product_reviews','promo_codes','blog_posts',
    'bundles','bundle_items','social_posts'
  ]
  loop
    execute format(
      'create policy hm_admin_all on public.%I for all to authenticated
         using (public.is_admin()) with check (public.is_admin())', t);
  end loop;
end $$;

-- Visiteurs : lecture du contenu public.
